import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import test from "node:test";

const testDirectory = path.dirname(fileURLToPath(import.meta.url));
const staticRoot = path.resolve(testDirectory, "..");

test("地图组件从 map_context 获取图商上下文，并保留 HERE SDK 入口", async () => {
  const component = await readFile(path.join(staticRoot, "assets/js/pages/scenario-component-page.js"), "utf8");
  const appBootstrap = await readFile(path.join(staticRoot, "assets/js/init-alpine.js"), "utf8");
  const mapRuntimePreload = await readFile(path.join(staticRoot, "assets/js/utils/map-runtime-preload.js"), "utf8");
  const resultPage = await readFile(path.join(staticRoot, "assets/js/pages/solver-job-detail-page.js"), "utf8");
  const mapPage = await readFile(path.join(staticRoot, "assets/js/pages/solver-job-map-page.js"), "utf8");
  const scenarioDetail = await readFile(path.join(staticRoot, "pages/scenario-detail.html"), "utf8");
  const map = await readFile(path.join(staticRoot, "assets/js/utils/map.js"), "utf8");
  const amap = await readFile(path.join(staticRoot, "assets/js/utils/amap.js"), "utf8");
  const here = await readFile(path.join(staticRoot, "assets/js/utils/here.js"), "utf8");
  const scenarioCss = await readFile(path.join(staticRoot, "assets/css/scenario-business.source.css"), "utf8");

  assert.match(component, /getMapRuntimeContext\(\)/);
  assert.match(component, /mapContextForLocale/);
  assert.match(component, /map_context: mapContextForLocale\(this\.componentContext\?\.map_context, locale\)/);
  assert.match(appBootstrap, /warmMapRuntime\(\)\.catch\(\(\) => \{\}\)/);
  assert.match(mapRuntimePreload, /mapContextPromise = getJson\("\/map_context"\)/);
  assert.match(mapRuntimePreload, /script\.dataset\.vrpScenarioAmap = "true"/);
  assert.match(mapRuntimePreload, /script\.fetchPriority = "high"/);
  assert.match(mapRuntimePreload, /addConnectionHint\(url, "preconnect"\)/);
  assert.match(mapRuntimePreload, /export function invalidateMapRuntimeContext/);
  assert.match(scenarioDetail, /x-text="routingMatrixModeLabel\(\)"/);
  assert.match(map, /loadMap/);
  assert.match(amap, /provider === "here"/);
  assert.match(amap, /lang: amapLanguage\(mapContext\?\.locale\)/);
  assert.match(amap, /_vrpMapLocale = normalizedMapLocale\(mapContext\)/);
  assert.match(amap, /map\.setLang\(amapLanguage\(locale\)\)/);
  assert.match(amap, /function applyMapLocale/);
  assert.match(amap, /function mapLocaleRequiresRecreation/);
  assert.match(amap, /const DEFAULT_MAP_STYLE = DARK_MAP_STYLE/);
  assert.match(amap, /mapTheme: options\.mapTheme/);
  assert.match(amap, /applyAmapEnglishDarkFallback/);
  assert.match(scenarioCss, /\.amap-container\.vrp-amap-en-dark-fallback \.amap-layer:not\(\.amap-vectors\)/);
  assert.match(resultPage, /recreatePreviewMapForLocale/);
  assert.match(mapPage, /mapLocaleRequiresRecreation\(map\)/);
  assert.match(mapPage, /mapTheme: "dark"/);
  assert.match(mapPage, /refreshOverlays: options\.refreshOverlays === true/);
  assert.match(mapPage, /renderMap\(\{ refreshOverlays: true \}\)/);
  assert.ok(here.includes("mapsjs-core"));
  assert.match(here, /loadHereAsAmapCompatibility/);
  assert.match(here, /name === "click" \? "tap" : name/);
  assert.match(here, /class HerePolyline[\s\S]*fitPoints\(\)/);
  assert.match(here, /new window\.H\.map\.Group\(\)/);
  assert.match(here, /group\.getBoundingBox\?\.\(\)/);
  assert.doesNotMatch(here, /object\.getBoundingBox\(\)/);
  assert.match(here, /if \(options\.strokeStyle === "dashed"\) \{\s*style\.lineDash = \[10, 5\];/);
  assert.doesNotMatch(here, /lineDash: options\.strokeStyle/);
  assert.match(here, /strokeColor: withOpacity\(options\.strokeColor \|\| "#34d399", options\.strokeOpacity\)/);
  assert.doesNotMatch(here, /lineDashImage:/);
  assert.match(here, /class HereCircleMarker[\s\S]*new H\.map\.Marker/);
  assert.doesNotMatch(here, /new H\.map\.Circle\(/);
  assert.match(here, /new H\.map\.DomMarker/);
  assert.match(here, /HERE_SMALL_MARKER_HEAD_OFFSET_Y = -26\.125/);
  assert.match(here, /labelAnchor === "pin-head"/);
  assert.match(here, /options\.vrpLabelAnchor/);
  assert.match(amap, /vrpLabelAnchor: "pin-head"/);
  assert.match(amap, /width:25px;height:25px/);
  assert.match(here, /class PixelCompat/);
  assert.match(here, /loadCss\(hereUrls\(context\)\?\.css, container\?\.getRootNode\?\.\(\)\)/);
  assert.match(here, /this\._behavior\?\.disable\?\.\(\)/);
  assert.match(here, /function dayBaseLayer\(layers\)/);
  assert.match(here, /function nightBaseLayer\(layers\)/);
  assert.match(here, /function baseLayerForTheme\(layers, theme\)/);
  assert.match(here, /layers\?\.vector\?\.normal\?\.mapnight/);
  assert.match(here, /layers\?\.raster\?\.normal\?\.mapnight/);
  assert.match(here, /this\._mapTheme = mapThemeFromStyle\(options\.mapStyle\)/);
  assert.match(here, /const baseLayer = baseLayerForTheme\(layers, this\._mapTheme\)/);
  assert.match(here, /this\._map\.setBaseLayer\?\.\(baseLayer\)/);
  assert.match(here, /platform\.createDefaultLayers\(\{ pois: false, lg: hereLanguage\(context\?\.locale\) \}\)/);
  assert.match(here, /setMapLocale\(locale\)/);
  assert.match(here, /setMapStyle\(mapStyle\)/);
  assert.match(here, /createDefaultLayers\(\{ pois: false, lg: language \}\)/);
  assert.match(here, /size: \{ w: 30, h: 40 \}/);
  assert.match(here, /HERE_VIEWPORT_PADDING = \{ top: 60, right: 40, bottom: 40, left: 40 \}/);
  assert.match(here, /padding: HERE_VIEWPORT_PADDING/);
  assert.match(here, /must not apply AMap's additional/);
  assert.match(here, /Math\.min\(cappedMaxZoom, fittedZoom\)/);
  assert.doesNotMatch(here, /HERE_FIT_VIEW_ZOOM_IN_DELTA/);
});
