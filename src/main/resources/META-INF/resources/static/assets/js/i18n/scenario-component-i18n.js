const ENGLISH_COMPONENT_SOURCE_TEXT = new Map(
  Object.entries(COMPONENT_TEXT["en-US"]).map(([source, translated]) => [translated, source])
);

export function normalizeComponentLocale(value) {
  return SUPPORTED.has(value) ? value : COMPONENT_DEFAULT_LOCALE;
}

export function componentMessageKeys() {
  return Object.keys(COMPONENT_MESSAGES[COMPONENT_DEFAULT_LOCALE]);
}

function substitute(value, params = {}) {
  return String(value).replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, key) => String(params?.[key] ?? ""));
}

export function createScenarioComponentI18n(initialLocale, root) {
  let locale = normalizeComponentLocale(initialLocale);
  const textSources = new WeakMap();
  const attributeSources = new WeakMap();
  const attributes = ["aria-label", "title", "placeholder", "alt"];
  let observer = null;

  function t(key, params = {}, activeLocale = locale) {
    const normalizedLocale = normalizeComponentLocale(activeLocale);
    const message = COMPONENT_MESSAGES[normalizedLocale]?.[key];
    if (message != null) {
      return substitute(message, params);
    }
    return substitute(COMPONENT_MESSAGES[normalizedLocale]["i18n.missing"], { key });
  }

  function translateText(value, params = {}) {
    const source = String(value ?? "");
    if (locale === COMPONENT_DEFAULT_LOCALE) {
      return substitute(ENGLISH_COMPONENT_SOURCE_TEXT.get(source.trim()) || source, params);
    }
    const leading = source.match(/^\s*/)?.[0] || "";
    const trailing = source.match(/\s*$/)?.[0] || "";
    return leading + substitute(COMPONENT_TEXT["en-US"][source.trim()] || source.trim(), params) + trailing;
  }

  function localizeError(error) {
    const code = error?.errorCode || error?.code || error?.payload?.error_code || error?.payload?.errorCode
      || (error?.status ? "internal_error" : "network_error");
    const params = error?.errorParams || error?.params || error?.payload?.error_params || error?.payload?.errorParams || {};
    return substitute((COMPONENT_ERRORS[locale] || COMPONENT_ERRORS[COMPONENT_DEFAULT_LOCALE])[code]
      || (COMPONENT_ERRORS[locale] || COMPONENT_ERRORS[COMPONENT_DEFAULT_LOCALE]).internal_error, params);
  }

  function translateTextNode(node) {
    if (!node || node.nodeType !== Node.TEXT_NODE) return;
    const dynamic = node.parentElement?.hasAttribute?.("x-text");
    if (!dynamic && !textSources.has(node)) textSources.set(node, node.nodeValue || "");
    const next = translateText(dynamic ? node.nodeValue : textSources.get(node));
    if (node.nodeValue !== next) node.nodeValue = next;
  }

  function translateElement(element) {
    if (!element || element.nodeType !== Node.ELEMENT_NODE) return;
    attributes.forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      let sources = attributeSources.get(element);
      if (!sources) { sources = new Map(); attributeSources.set(element, sources); }
      const dynamic = element.hasAttribute(`:${attribute}`) || element.hasAttribute(`x-bind:${attribute}`);
      if (!dynamic && !sources.has(attribute)) sources.set(attribute, element.getAttribute(attribute) || "");
      const next = translateText(dynamic ? element.getAttribute(attribute) : sources.get(attribute));
      if (element.getAttribute(attribute) !== next) element.setAttribute(attribute, next);
    });
    [...element.childNodes].forEach(translateTextNode);
  }

  function translateTree(target = root) {
    if (!target) return;
    if (target.nodeType === Node.ELEMENT_NODE) translateElement(target);
    target.querySelectorAll?.("*").forEach(translateElement);
  }

  function observe() {
    if (!root || observer || typeof MutationObserver === "undefined"
      || !root.hasAttribute?.("data-i18n-legacy-root")) return;
    observer = new MutationObserver((records) => records.forEach((record) => {
      if (record.type === "characterData") return translateTextNode(record.target);
      if (record.type === "attributes") return translateElement(record.target);
      if (record.type === "childList") record.addedNodes.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
        if (node.nodeType === Node.ELEMENT_NODE) translateTree(node);
      });
    }));
    observer.observe(root, { attributes: true, attributeFilter: attributes, childList: true, characterData: true, subtree: true });
    translateTree();
  }

  function setLocale(value) {
    locale = normalizeComponentLocale(value);
    root?.setAttribute?.("lang", locale);
    translateTree();
    return locale;
  }

  setLocale(locale);
  return {
    getLocale: () => locale,
    setLocale,
    t,
    // Deprecated source-text compatibility API. New component UI uses t(key).
    translateText,
    localizeError,
    translateTree,
    observe,
    disconnect: () => observer?.disconnect()
  };
}
